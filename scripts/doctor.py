def check_vc6():
    section("4. VC6 (cl 12.00.8168)")
    root = vc6.find_root()
    if root is None:
        report("fail", "VC6 root", "not found",
               "copy CD 1 of VS 6.0 Enterprise into %s, or set VC6_ROOT"
               % (ROOT.parent / "tools" / "vc6"))
        return
    report("ok", "VC6 root", str(root))
    bad = []
    for rel, ref in VC6_FILES.items():
        p = root
        for part in rel.split("/"):
            p = vc6._child(p, part)
        if not p.exists():
            bad.append(rel + " missing")
        elif sha256(p) != ref:
            bad.append(rel + " differs")
    report("ok" if not bad else "fail", "VC6 files (%d)" % len(VC6_FILES),
           "SHA-256 as expected" if not bad else "; ".join(bad),
           "a copy of CD 1 without any service pack is required (notes/toolchain-vc6.md §1)")
    vc = vc6.VC6(root)
    for t, want in (("cl", "12.00.8168"), ("link", "6.00.8168")):
        try:
            rc, out = vc.run([t])
        except OSError as e:
            report("fail", t, str(e), "Wine does not run the VC6 tools")
            return
        m = re.search(r"Version ([\d.]+)", out)
        got = m.group(1) if m else "?"
        report("ok" if got == want else "fail", t + " runs", got,
               "output: " + out[:200].replace("\n", " "))
    work = ROOT / "captures" / "doctor"
    work.mkdir(parents=True, exist_ok=True)
    for f in work.glob("t.*"):
        f.unlink()
    (work / "t.c").write_text("int f(int a) { return a * 3; }\n", encoding="ascii")
    rc, out = vc.run(["cl", "/nologo", "/O2", "/c", "t.c"], cwd=work)
    ok = rc == 0 and (work / "t.obj").exists()
    report("ok" if ok else "fail", "Compilation /O2", "t.obj produced" if ok else out[:300])


