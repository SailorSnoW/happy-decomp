def nix_ghidra():
    """Ghidra installed by Nix (nixpkgs `ghidra` or `ghidra.withExtensions`).

    Returns {"inst", "ext", "java"} for the `ghidra` found in the PATH, {} otherwise.
    The nixpkgs wrappers are compiled programs (makeCWrapper) whose strings name the
    wrapped Ghidra, NIX_GHIDRAHOME (extensions added by withExtensions) and the JDK
    put in the PATH by support/launch.sh. Java is not necessarily in the user's PATH.
    """
    exe = shutil.which("ghidra")
    if not exe:
        return {}
    real = pathlib.Path(exe).resolve()
    if not str(real).startswith("/nix/store/"):
        return {}

    def strings(p):
        try:
            return p.read_bytes().decode("latin-1")
        except OSError:
            return ""

    res = {}
    if (real.parent / "Ghidra" / "application.properties").exists():
        res["inst"] = real.parent                      # .../lib/ghidra/ghidraRun
    else:
        txt = strings(real)
        m = re.search(r"(/nix/store/[^\0\s'\"]+/bin/ghidra)(?![-\w])", txt)
        if m:
            res["inst"] = pathlib.Path(m.group(1)).resolve().parent
        m = re.search(r"NIX_GHIDRAHOME=(/nix/store/[^\0\s'\"]+)", txt)
        if m:
            res["ext"] = pathlib.Path(m.group(1))
    if "inst" in res:
        m = re.search(r"(/nix/store/[^\0\s'\"]*jdk[^\0\s'\"]*)/bin",
                      strings(res["inst"] / "support" / "launch.sh"))
        if m:
            res["java"] = str(pathlib.Path(m.group(1)) / "bin" / "java")
    return res


def ghidra_candidates(nix):
    name = "ghidra_%s_PUBLIC" % GHIDRA_VERSION
    c = []
    if os.environ.get("GHIDRA_INSTALL_DIR"):
        c.append(pathlib.Path(os.environ["GHIDRA_INSTALL_DIR"]))
    home = pathlib.Path.home()
    c += [ROOT.parent / "tools" / name, home / name]
    if WIN:
        c += [pathlib.Path(d + ":/") / name for d in "CDE"]
    if MAC:
        c += [pathlib.Path("/Applications") / name, home / "Applications" / name]
    if "inst" in nix:
        c.append(nix["inst"])
    return c


def ghidra_settings_dirs():
    # The settings folder is named after application.release.name: NIX for nixpkgs.
    names = ["ghidra_%s_%s" % (GHIDRA_VERSION, r) for r in ("PUBLIC", "NIX")]
    home = pathlib.Path.home()
    if WIN:
        base = [pathlib.Path(os.environ.get("APPDATA", home)) / "ghidra" / n for n in names]
    elif MAC:
        base = [home / "Library" / "ghidra" / n for n in names]
    else:
        base = [pathlib.Path(os.environ.get("XDG_CONFIG_HOME", home / ".config"))
                / "ghidra" / n for n in names]
    return base + [home / ".ghidra" / ("." + n) for n in names]


def java_major(nix):
    cands = []
    if os.environ.get("JAVA_HOME"):
        cands.append(str(pathlib.Path(os.environ["JAVA_HOME"]) / "bin" / "java"))
    if shutil.which("java"):
        cands.append(shutil.which("java"))
    if "java" in nix:
        cands.append(nix["java"])
    for j in cands:
        rc, out = sh([j, "-version"])
        m = re.search(r'version "(\d+)', out or "")
        if rc == 0 and m:
            return int(m.group(1)), j
    return None, None


def check_ghidra():
    section("5. Ghidra %s + GhidraMCP 7.0.0" % GHIDRA_VERSION)
    nix = nix_ghidra()
    major, j = java_major(nix)
    report("ok" if major and major >= 21 else "fail", "Java (JDK 21 or later)",
           "%s (%s)" % (major, j) if major else "not found",
           "SKILL.md §5 (Temurin 21)")
    inst = next((c for c in ghidra_candidates(nix)
                 if (c / "Ghidra" / "application.properties").exists()), None)
    if inst is None:
        report("fail", "Installation", "not found",
               "unzip ghidra_%s_PUBLIC or set GHIDRA_INSTALL_DIR" % GHIDRA_VERSION)
    else:
        props = (inst / "Ghidra" / "application.properties").read_text(errors="replace")
        m = re.search(r"application\.version=(\S+)", props)
        ver = m.group(1) if m else "?"
        report("ok" if ver == GHIDRA_VERSION else "fail", "Installation",
               "%s (%s)" % (ver, inst),
               "exactly 12.1.4: under 12.2, decompilation fails (CLAUDE.md)")
        plat = ("win_x86_64" if WIN else
                ("mac_arm_64" if platform.machine() == "arm64" else "mac_x86_64") if MAC
                else "linux_x86_64")
        dec = inst / "Ghidra/Features/Decompiler/os" / plat / (
            "decompile.exe" if WIN else "decompile")
        report("ok" if dec.exists() else "fail", "Native decompiler (%s)" % plat,
               "present" if dec.exists() else "missing",
               "run %s (Xcode CLT + Gradle)" % (inst / "support" / "buildNatives"))
        if MAC and dec.exists():
            rc, _ = sh(["xattr", "-p", "com.apple.quarantine", str(dec)])
            report("warn" if rc == 0 else "ok", "Gatekeeper quarantine",
                   "present" if rc == 0 else "lifted",
                   "xattr -dr com.apple.quarantine '%s'" % inst)
    ext = None
    dirs = (ghidra_settings_dirs() + ([inst / "Ghidra"] if inst else [])
            + ([nix["ext"]] if "ext" in nix else []))
    for d in dirs:
        p = d / "Extensions" / "GhidraMCP" / "extension.properties"
        if p.exists():
            ext = p
            break
    if ext is None:
        report("fail", "GhidraMCP extension", "not installed",
               "Ghidra > File > Install Extensions > GhidraMCP-7.0.0.zip")
    else:
        txt = ext.read_text(errors="replace")
        ok = "version=%s" % GHIDRA_VERSION in txt and "Plugin version 7.0.0" in txt
        report("ok" if ok else "fail", "GhidraMCP extension",
               "7.0.0 for %s (%s)" % (GHIDRA_VERSION, ext.parent) if ok
               else "unexpected version (%s)" % ext, "GhidraMCP-7.0.0.zip from release v7.0.0")
    try:
        n = len(http_json("mcp/schema", timeout=5)["tools"])
    except (OSError, ValueError, KeyError) as e:
        report("warn", "GhidraMCP server (8089)", "unreachable (%s)" % e.__class__.__name__,
               "start Ghidra, open the 3 programs, Tools > GhidraMCP > Start MCP Server")
        return
    report("ok" if n == MCP_TOOLS else "warn", "GhidraMCP server (8089)", "%d tools" % n,
           "%d expected" % MCP_TOOLS)
    try:
        progs = {p["name"] for p in http_json("list_open_programs", 30)["programs"]}
    except (OSError, ValueError, KeyError) as e:
        report("fail", "Open programs", str(e))
        return
    for name, want in FUNCTIONS.items():
        if name not in progs:
            report("fail", name, "not open in Ghidra",
                   "import it into the happy-decomp project and open it in CodeBrowser")
            continue
        try:
            got = http_json("find_functions?program=%s&limit=1" % name, 60)["total"]
        except (OSError, ValueError, KeyError) as e:
            report("fail", name, str(e))
            continue
        if got == FRESH[name]:
            report("warn", name, "%d functions (fresh import)" % got,
                   "%d in the reference project: restore the .gar (SKILL.md §5)" % want)
            continue
        report("ok" if got == want else "fail", name, "%d functions" % got,
               "%d expected: analysis differs from the reference (SKILL.md §5)" % want)


