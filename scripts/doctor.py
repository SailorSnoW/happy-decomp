def report(status, label, detail="", hint=""):
    results.append(status)
    print("  %s %s%s" % (TAGS[status], label, ": " + detail if detail else ""))
    if hint and status in ("warn", "fail"):
        print("          -> " + hint)


def section(title):
    print("\n== " + title)


def sh(args, cwd=None, timeout=120, env=None):
    """Runs a command; returns (code, output) or (None, message)."""
    try:
        p = subprocess.run(args, cwd=cwd, capture_output=True, text=True,
                           errors="replace", timeout=timeout, env=env)
        return p.returncode, (p.stdout + p.stderr).strip()
    except (OSError, subprocess.TimeoutExpired) as e:
        return None, str(e)


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def http_json(path, timeout=10):
    with urllib.request.urlopen(GHIDRA_URL + path, timeout=timeout) as r:
        return json.loads(r.read().decode("utf-8"))


