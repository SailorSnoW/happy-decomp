# --- 1. System -----------------------------------------------------------------

def check_system():
    section("1. System")
    report("ok", "Platform", "%s %s (%s)" % (platform.system(), platform.release(),
                                              platform.machine()))
    v = sys.version_info
    report("ok" if v >= (3, 8) else "fail", "Python running doctor",
           "%d.%d.%d (the project uses the .venv one)" % v[:3], "Python 3.8 or later")
    git = shutil.which("git")
    report("ok" if git else "fail", "git", git or "missing", "install git")
    if WIN:
        report("skip", "Wine", "not needed on Windows")
        return
    if MAC and platform.machine() == "arm64":
        # Full path: GNU coreutils (Nix, Homebrew) has an `arch` without -x86_64.
        rc, _ = sh(["/usr/bin/arch", "-x86_64", "/usr/bin/true"])
        report("ok" if rc == 0 else "fail", "Rosetta 2",
               "present" if rc == 0 else "missing",
               "softwareupdate --install-rosetta --agree-to-license")
    for t in ("wine", "winepath"):
        p = shutil.which(t)
        if not p:
            report("fail", t, "not in PATH",
                   "SKILL.md, macOS §Wine (reccmp calls `wine` and `winepath` by name)")
            continue
        if t == "wine":
            rc, out = sh([p, "--version"], timeout=60)
            report("ok" if rc == 0 else "fail", t, "%s (%s)" % (out, p),
                   "Wine does not start")
        else:
            report("ok", t, p)


