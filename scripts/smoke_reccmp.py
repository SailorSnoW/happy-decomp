"""End-to-end test of the matching toolchain: VC6 + Allegro headers + reccmp.

Repeats the test of notes/toolchain-vc6.md §6 in captures/smoke/ (wiped on
every run):
1. import library alleg40.lib generated by LIB /DEF from
   3rdparty/allegro-4.0.3/lib/msvc/allegro.def;
2. compilation (cl /O2 /Zi) of the 5 functions of notes/decompme-candidates.md §10,
   with the reccmp annotations, and link /DEBUG /INCREMENTAL:NO /OPT:REF into
   happy.exe;
3. reccmp-project create / detect, reccmp-reccmp --json, reccmp-datacmp.

Expected: the 5 functions at 100%, and _free (LIBRARY annotation) matched.
Exit code 0 if so, 1 otherwise. Only reads game/, read-only.
On macOS/Linux, VC6 and reccmp's cvdump go through Wine.

Usage: .venv/Scripts/python scripts/smoke_reccmp.py   (macOS: .venv/bin/python)
"""
import json
import pathlib
import shutil
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from vc6 import VC6  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "captures" / "smoke"
ALLEGRO = ROOT / "3rdparty" / "allegro-4.0.3"
EXPECTED = ("0x406c80", "0x409010", "0x40a9a0", "0x40ab00", "0x40ac10")

SMOKE_C = r'''
#include <allegro.h>
#include <stdlib.h>
#include <string.h>

typedef struct TILE5 {
    unsigned char t0;
    unsigned char t1;
    unsigned char t2;
    unsigned char t3;
    unsigned char t4;
} TILE5;

typedef struct MAP5 {
    unsigned char f00;
    unsigned char f01;
    unsigned char f02;
    unsigned char f03[2];
    char f05[0x50];
    char f55[0x22];
    unsigned char f77[0x11];
    TILE5 *f88;
} MAP5;

// GLOBAL: HAPPY 0x00442084
volatile int DAT_00442084;
// GLOBAL: HAPPY 0x0042f52c
int DAT_0042f52c;
// GLOBAL: HAPPY 0x0042f530
int DAT_0042f530;
// GLOBAL: HAPPY 0x00413b24
int DAT_00413b24;
// GLOBAL: HAPPY 0x00413b28
int DAT_00413b28;
// GLOBAL: HAPPY 0x004450b4
DATAFILE *DAT_004450b4;

// FUNCTION: HAPPY 0x00406c80
int FUN_00406c80(int ms)
{
    int n;

    n = ms / 15;
    DAT_00442084 = 0;
    while (DAT_00442084 < n && !key[KEY_ESC])
        ;
    return key[KEY_ESC] != 0;
}

// FUNCTION: HAPPY 0x00409010
void FUN_00409010(int a, int b)
{
    if (a != 0) {
        DAT_0042f530++;
        if (DAT_0042f530 == 8) {
            DAT_0042f530 = 0;
            DAT_0042f52c++;
            if (DAT_0042f52c > 1)
                DAT_0042f52c = 0;
        }
    }
    if (b != 0) {
        DAT_00413b24++;
        if (DAT_00413b24 == 8) {
            DAT_00413b24 = 0;
            DAT_00413b28++;
            if (DAT_00413b28 > 1)
                DAT_00413b28 = 0;
        }
    }
}

// FUNCTION: HAPPY 0x0040a9a0
void FUN_0040a9a0(MAP5 *m)
{
    int x;
    int y;
    int i;

    if (m != NULL) {
        memset(m->f88, 0, m->f02 * m->f01 * sizeof(TILE5));
        for (x = 0; x < m->f01; x++) {
            for (y = 0; y < m->f02; y++) {
                i = m->f01 * y + x;
                m->f88[i].t0 = 0;
                m->f88[i].t1 = 0;
                m->f88[i].t2 = 0;
            }
        }
    }
}

// FUNCTION: HAPPY 0x0040ab00
void FUN_0040ab00(MAP5 *m)
{
    if (m->f88 != NULL)
        free(m->f88);
    if (m != NULL)
        free(m);
}

// FUNCTION: HAPPY 0x0040ac10
int FUN_0040ac10(const char *filename)
{
    if (DAT_004450b4 != NULL)
        unload_datafile(DAT_004450b4);
    DAT_004450b4 = load_datafile(filename);
    return DAT_004450b4 != NULL;
}

int main(int argc, char *argv[])
{
    allegro_init();
    FUN_00406c80(argc);
    FUN_00409010(argc, argc);
    FUN_0040a9a0((MAP5 *)argv);
    FUN_0040ab00((MAP5 *)argv);
    return FUN_0040ac10(argv[0]);
}
END_OF_MAIN();
'''

# Never compiled: reccmp only reads the annotations in it.
LIBRARY_H = '''#ifdef 0
// LIBRARY: HAPPY 0x0040b463
// _free

// LIBRARY: HAPPY 0x0040b492
// _malloc
#endif
'''


def step(title, rc, out):
    print("== %s: %s" % (title, "ok" if rc == 0 else "FAILED (code %d)" % rc))
    if rc != 0:
        print(out.strip())
        sys.exit(1)


def tool(name, *args):
    exe = shutil.which(name)
    if exe is None:
        print("== %s not found in PATH" % name)
        sys.exit(1)
    p = subprocess.run([exe, *args], cwd=OUT, capture_output=True, text=True,
                       errors="replace")
    return p.returncode, p.stdout + p.stderr


def main():
    vc = VC6()
    if OUT.exists():
        shutil.rmtree(OUT)
    (OUT / "src").mkdir(parents=True)
    (OUT / "build").mkdir()
    (OUT / "src" / "smoke.c").write_text(SMOKE_C.lstrip(), encoding="ascii")
    (OUT / "src" / "library_crt.h").write_text(LIBRARY_H, encoding="ascii")

    step("LIB /DEF (alleg40.lib)", *vc.run([
        "lib", "/NOLOGO", "/DEF:" + vc.path(ALLEGRO / "lib" / "msvc" / "allegro.def"),
        "/MACHINE:IX86", "/NAME:alleg40.dll", "/OUT:alleg40.lib"], cwd=OUT / "build"))
    step("cl /O2 /Zi", *vc.run([
        "cl", "/nologo", "/O2", "/Zi", "/c", "/I", vc.path(ALLEGRO / "include"),
        "/Fosmoke.obj", "/Fdsmoke.pdb", vc.path(OUT / "src" / "smoke.c")],
        cwd=OUT / "build"))
    step("link /DEBUG /INCREMENTAL:NO /OPT:REF", *vc.run([
        "link", "/nologo", "/SUBSYSTEM:WINDOWS", "/DEBUG", "/INCREMENTAL:NO",
        "/OPT:REF", "/OUT:happy.exe", "/PDB:happy.pdb", "smoke.obj",
        "alleg40.lib", "kernel32.lib"], cwd=OUT / "build"))

    step("reccmp-project create", *tool(
        "reccmp-project", "create", "--originals", str(ROOT / "game" / "happy.exe"),
        "--path", str(OUT)))
    step("reccmp-project detect", *tool(
        "reccmp-project", "detect", "--what", "recompiled", "--search-path", "build"))
    rc, out = tool("reccmp-reccmp", "--target", "HAPPY", "--json", "reccmp.json",
                   "--no-color")
    step("reccmp-reccmp", rc, out)
    step("reccmp-datacmp", *tool("reccmp-datacmp", "--target", "HAPPY", "--no-color"))

    data = {d["address"]: d for d in
            json.loads((OUT / "reccmp.json").read_text(encoding="utf-8"))["data"]}
    ok = True
    print("== Results")
    for a in EXPECTED:
        m = data.get(a, {}).get("matching")
        good = m == 1.0
        ok &= good
        print("  %s %-14s %s" % ("ok  " if good else "FAIL", a,
                                 "missing" if m is None else "%.2f %%" % (100 * m)))
    free = data.get("0x40b463", {})
    good = free.get("name") == "_free" and free.get("library")
    ok &= bool(good)
    print("  %s 0x40b463       _free (LIBRARY) %s" % (
        "ok  " if good else "FAIL", "matched" if good else "not matched"))
    print("== %s" % ("SUCCESS: 5/5 at 100%" if ok else "FAILED"))
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
